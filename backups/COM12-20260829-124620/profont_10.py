def draw(fb, s, x, y):
    """Draw string to framebuffer at (x, y). Optimized for monospaced."""
    bpr = (5 + 7) // 8  # bytes per row
    for ch in s:
        entry = _GLYPHS.get(ord(ch))
        if entry is None:
            entry = _GLYPHS.get(ord('?'))
        if entry is None:
            x += CHAR_WIDTH + 1
            continue
        w, bmp = entry
        for row in range(10):
            for col in range(w):
                byte_idx = row * bpr + (col >> 3)
                if bmp[byte_idx] & (0x80 >> (col & 7)):
                    fb.pixel(x + col, y + row, 1)
        x += w + 1
    return x


def text_width(s):
    """Calculate pixel width of a string."""
    if not s:
        return 0
    return len(s) * (CHAR_WIDTH + 1) - 1
